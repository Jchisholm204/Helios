int world_loader(struct grid* pGrid, enum eWorlds world) {
    if (!pGrid)
        return -1;
    if (!pGrid->voxels)
        return -1;

    // Verify the grid is at least the size of the worlds
    if (pGrid->size.x < WORLD_X)
        return -3;
    if (pGrid->size.y < WORLD_Y)
        return -3;

    // Figure out what world to use
    int(*w)[WORLD_Y];
    switch (world) {
    case eWorld1A:
        w = w1a;
        break;
    case eWorld1B:
        w = w1b;
        break;
    case eWorld2A:
        w = w2a;
        break;
    case eWorld2B:
        w = w2b;
        break;
    case eWorld2C:
        w = w2c;
        break;
    default:
        w = NULL;
        break;
    }
    if (!w)
        return -2;

    // Load the world
    for (size_t x = 0; x < WORLD_X; x++) {
        for (size_t y = 0; y < WORLD_Y; y++) {
            struct voxel* v = grid_index(pGrid, x, y);
            if (!v)
                continue;
            int val = w[y][x];
            if (val == 1) {
                v->state = eStateBlocked;
            } else if (val == 2) {
                v->state = eStateSource;
            } else if (val == 3) {
                v->state = eStateGoal;
            } else {
                v->state = eStateEmpty;
            }
        }
    }
    return 0;
}

int world_updater(struct grid* pGrid, enum eWorlds world, struct queued_voxel **queue) {
    if (!pGrid)
        return -1;
    if (!pGrid->voxels)
        return -1;

    // Verify the grid is at least the size of the worlds
    if (pGrid->size.x < WORLD_X)
        return -3;
    if (pGrid->size.y < WORLD_Y)
        return -3;

    // Figure out what world to use
    int(*w)[WORLD_Y];
    switch (world) {
    case eWorld1A:
        w = w1a;
        break;
    case eWorld1B:
        w = w1b;
        break;
    case eWorld2A:
        w = w2a;
        break;
    case eWorld2B:
        w = w2b;
        break;
    case eWorld2C:
        w = w2c;
        break;
    default:
        w = NULL;
        break;
    }
    if (!w)
        return -2;

    // Load the world
    for (size_t x = 0; x < WORLD_X; x++) {
        for (size_t y = 0; y < WORLD_Y; y++) {
            struct voxel* v = grid_index(pGrid, x, y);
            if (!v)
                continue;
            int val = w[y][x];
            enum eVoxelState new_state;
            if (val == 1) {
                new_state = eStateBlocked;
            } else if (val == 2) {
                new_state = eStateSource;
            } else if (val == 3) {
                new_state = eStateGoal;
            } else {
                new_state = eStateEmpty;
            }
            if (new_state != v->state){
                v->state = new_state;
                queue_push(queue, v, 0, 0);
            }
        }
    }
    return 0;
}
